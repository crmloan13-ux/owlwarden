#!/usr/bin/env node
/**
 * Regenerates RULES.md from the engine.
 *
 * The catalogue is written by hand nowhere. A rule's metadata and remediation
 * live next to its implementation, and this script reads them out — so the docs
 * cannot describe a rule that does not exist, or miss one that does.
 *
 *   node scripts/generate-rules-md.mjs
 *   node scripts/generate-rules-md.mjs --check   # CI: fail if out of date
 */
import { createRequire } from "node:module";
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";

const require = createRequire(import.meta.url);
const native = require("@dointhai/owlwarden-core-native");

const OUTPUT = fileURLToPath(new URL("../RULES.md", import.meta.url));

const rules = JSON.parse(native.listRules());
const presets = JSON.parse(native.listPresets());
const coverage = JSON.parse(native.coverage());

const lines = [
  "<!-- Generated by scripts/generate-rules-md.mjs. Do not edit by hand. -->",
  "",
  "# Rules",
  "",
  `${rules.length} rule${rules.length === 1 ? "" : "s"} in owlwarden ${native.engineVersion()}.`,
  "",
  "Rule ids are permanent. They appear in suppressions, in agent rules files, and",
  "in other people's CI configs, so they are treated as public API.",
  "",
  "## Presets",
  "",
  "| Preset | Rules | What it is for |",
  "| --- | --- | --- |",
];

for (const preset of presets) {
  const contents = preset.rules.length === 0 ? "all" : preset.rules.join(", ");
  lines.push(`| \`${preset.name}\` | ${contents} | ${preset.description} |`);
}

lines.push(
  "",
  "## OWASP Top 10 (2021) coverage",
  "",
  `${coverage.categoriesCovered} of 10 categories have at least one rule.`,
  "",
  "The gaps are listed on purpose. A table showing only what is checked would",
  "be an advertisement; what a reader needs to know is what owlwarden is *not*",
  "looking at in their codebase, so that a clean report is read correctly.",
  "",
  "**Reach** says whether source analysis can see the category at all. A",
  "category with no rules and `poor` reach is a limit of the method, not a",
  "backlog item — no parser finds a design flaw. Those need the dynamic engine",
  "or a human.",
  "",
  "| Category | Reach | Rules |",
  "| --- | --- | --- |",
);

for (const entry of coverage.owasp) {
  const covering =
    entry.rules.length === 0
      ? entry.reachability === "poor"
        ? "*not reachable from source*"
        : "*none yet*"
      : entry.rules.map((id) => `\`${id}\``).join(", ");
  lines.push(`| **${entry.id}** ${entry.title} | ${entry.reachability} | ${covering} |`);
}

lines.push(
  "",
  "`owlwarden coverage` prints this from the engine you have installed, which",
  "is the version that matters if you are running a plugin or an older release.",
  "",
  "## Framework support",
  "",
  "Every rule carries remediation written for each framework, not one generic",
  "paragraph. A rule shipping without advice for a supported framework fails the",
  "build, so this column cannot silently drift to zero.",
  "",
  "| Framework | Rules with framework-specific remediation |",
  "| --- | --- |",
);

for (const framework of coverage.frameworks) {
  lines.push(`| \`${framework.id}\` | ${framework.rulesWithSpecificFix} of ${rules.length} |`);
}

lines.push("", "## Catalogue", "");

for (const rule of rules) {
  const tags = [
    `**${rule.severity}**`,
    `confidence at most \`${rule.maxConfidence}\``,
    rule.owasp ? `[OWASP ${rule.owasp}](https://owasp.org/Top10/)` : undefined,
    rule.cwe ? `[CWE-${rule.cwe}](https://cwe.mitre.org/data/definitions/${rule.cwe}.html)` : undefined,
  ].filter(Boolean);

  const explanation = JSON.parse(native.explainRule(rule.id) ?? "null");

  lines.push(
    `### \`${rule.id}\``,
    "",
    rule.title,
    "",
    tags.join(" · "),
    "",
    rule.description,
    "",
    "**Fixes**",
    "",
  );

  for (const fix of explanation?.fixes ?? []) {
    lines.push(`- *${fix.framework ?? "any framework"}* — ${fix.summary}`);
    if (fix.patch) {
      lines.push("", "  ```ts", ...fix.patch.split("\n").map((line) => `  ${line}`), "  ```");
    }
  }

  lines.push("", `\`owlwarden explain ${rule.id}\` prints this in the terminal.`, "");
}

const generated = `${lines.join("\n").replace(/\n{3,}/g, "\n\n").trimEnd()}\n`;

if (process.argv.includes("--check")) {
  const existing = readFileSync(OUTPUT, "utf8");
  if (existing !== generated) {
    process.stderr.write(
      "RULES.md is out of date. Run `node scripts/generate-rules-md.mjs`.\n",
    );
    process.exitCode = 1;
  }
} else {
  writeFileSync(OUTPUT, generated);
  process.stdout.write(`wrote ${OUTPUT}\n`);
}
