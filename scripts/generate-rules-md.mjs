#!/usr/bin/env node
/**
 * Regenerates RULES.md from the engine.
 *
 * The catalogue is written by hand nowhere. A rule's metadata and remediation
 * live next to its implementation, and this script reads them out — so the docs
 * cannot describe a rule that does not exist, or miss one that does.
 *
 *   node scripts/generate-rules-md.mjs
 *   node scripts/generate-rules-md.mjs --check   # CI: fail if out of date
 */
import { createRequire } from "node:module";
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";

const require = createRequire(import.meta.url);
const native = require("@dointhai/owlwarden-core-native");

const OUTPUT = fileURLToPath(new URL("../RULES.md", import.meta.url));

const rules = JSON.parse(native.listRules());
const presets = JSON.parse(native.listPresets());
const coverage = JSON.parse(native.coverage());

const webAppRules = rules.filter((rule) => (rule.surface ?? "webApp") === "webApp");
const agentRules = rules.filter((rule) => rule.surface === "agentWorkspace");

/** The profile label for one fix: a framework, an agent host, or neither. */
const fixProfile = (fix) => fix.host ?? fix.framework ?? "any profile";

const lines = [
  "<!-- Generated by scripts/generate-rules-md.mjs. Do not edit by hand. -->",
  "",
  "# Rules",
  "",
  `${rules.length} rule${rules.length === 1 ? "" : "s"} in owlwarden ${native.engineVersion()}:`,
  `${webAppRules.length} that read application source, and ${agentRules.length} that read the`,
  "agent and editor configuration in the working tree.",
  "",
  "Rule ids are permanent. They appear in suppressions, in agent rules files, and",
  "in other people's CI configs, so they are treated as public API.",
  "",
  "## Surfaces",
  "",
  "A rule declares which kind of artefact it reads, and that decides which set of",
  "fixes it owes. A `webApp` rule ships remediation for all twelve frameworks; an",
  "`agentWorkspace` rule ships remediation for all seven agent hosts. Neither is",
  "checked against the other's list, and a missing cell fails the build either way.",
  "",
  "| Surface | Rules | Profiles it must cover |",
  "| --- | --- | --- |",
  `| \`webApp\` | ${webAppRules.length} | ${coverage.frameworks.length} frameworks |`,
  `| \`agentWorkspace\` | ${agentRules.length} | ${coverage.hosts.length} agent hosts |`,
  "",
  "## Presets",
  "",
  "| Preset | Rules | What it is for |",
  "| --- | --- | --- |",
];

for (const preset of presets) {
  const contents = preset.rules.length === 0 ? "all" : preset.rules.join(", ");
  lines.push(`| \`${preset.name}\` | ${contents} | ${preset.description} |`);
}

lines.push(
  "",
  "## OWASP Top 10 (2021) coverage",
  "",
  `${coverage.categoriesCovered} of 10 categories have at least one rule.`,
  "",
  "The gaps are listed on purpose. A table showing only what is checked would",
  "be an advertisement; what a reader needs to know is what owlwarden is *not*",
  "looking at in their codebase, so that a clean report is read correctly.",
  "",
  "**Reach** says whether source analysis can see the category at all. A",
  "category with no rules and `poor` reach is a limit of the method, not a",
  "backlog item — no parser finds a design flaw. Those need the dynamic engine",
  "or a human.",
  "",
  "| Category | Reach | Rules |",
  "| --- | --- | --- |",
);

for (const entry of coverage.owasp) {
  const covering =
    entry.rules.length === 0
      ? entry.reachability === "poor"
        ? "*not reachable from source*"
        : "*none yet*"
      : entry.rules.map((id) => `\`${id}\``).join(", ");
  lines.push(`| **${entry.id}** ${entry.title} | ${entry.reachability} | ${covering} |`);
}

lines.push(
  "",
  "`owlwarden coverage` prints this from the engine you have installed, which",
  "is the version that matters if you are running a plugin or an older release.",
  "",
  `## OWASP ASI ${coverage.asiEdition} coverage`,
  "",
  `${coverage.asiCategoriesCovered} of 10 agentic categories have at least one rule.`,
  "",
  "A second taxonomy, kept separate on purpose. The Top 10 (2021) is about the web",
  "application in this repository; the ASI list is about the agent that works in",
  "it. Merging them would let an agent rule appear to raise Top 10 coverage, and",
  "the `owasp-top10` preset would stop meaning anything.",
  "",
  "The edition is pinned in the engine, so moving to a later one is a reviewed",
  "change rather than a drift. CWE is the primary mapping on every rule here.",
  "",
  "| Category | Reach | Rules |",
  "| --- | --- | --- |",
);

for (const entry of coverage.asi) {
  const covering =
    entry.rules.length === 0
      ? entry.reachability === "poor"
        ? "*not reachable from configuration*"
        : "*none yet*"
      : entry.rules.map((id) => `\`${id}\``).join(", ");
  lines.push(`| **${entry.id}** ${entry.title} | ${entry.reachability} | ${covering} |`);
}

lines.push(
  "",
  "## Framework support",
  "",
  "Every `webApp` rule carries remediation written for each framework, not one",
  "generic paragraph. A rule shipping without advice for a supported framework",
  "fails the build, so this column cannot silently drift to zero.",
  "",
  "| Framework | Rules with framework-specific remediation |",
  "| --- | --- |",
);

for (const framework of coverage.frameworks) {
  lines.push(
    `| \`${framework.id}\` | ${framework.rulesWithSpecificFix} of ${webAppRules.length} |`,
  );
}

lines.push(
  "",
  "## Agent host support",
  "",
  "The same invariant, one surface over. Every `agentWorkspace` rule names the",
  "host's own file and key in its fix — `.claude/settings.json` → `hooks.SessionStart`",
  "is a fix; \"remove the hook\" is advice.",
  "",
  "`generic` is not a placeholder. It is the fix for a host we have never heard",
  "of, and keeping it mandatory is what stops this family from becoming an",
  "advertisement for four vendors.",
  "",
  "| Agent host | Rules with host-specific remediation |",
  "| --- | --- |",
);

for (const host of coverage.hosts) {
  lines.push(`| \`${host.id}\` | ${host.rulesWithSpecificFix} of ${agentRules.length} |`);
}

lines.push("", "## Catalogue", "");

for (const rule of rules) {
  const tags = [
    `**${rule.severity}**`,
    `confidence at most \`${rule.maxConfidence}\``,
    `surface \`${rule.surface ?? "webApp"}\``,
    rule.owasp ? `[OWASP ${rule.owasp}](https://owasp.org/Top10/)` : undefined,
    rule.asi ? `[ASI ${rule.asi}](https://genai.owasp.org/)` : undefined,
    rule.cwe ? `[CWE-${rule.cwe}](https://cwe.mitre.org/data/definitions/${rule.cwe}.html)` : undefined,
  ].filter(Boolean);

  const explanation = JSON.parse(native.explainRule(rule.id) ?? "null");

  lines.push(
    `### \`${rule.id}\``,
    "",
    rule.title,
    "",
    tags.join(" · "),
    "",
    rule.description,
    "",
    "**Fixes**",
    "",
  );

  for (const fix of explanation?.fixes ?? []) {
    lines.push(`- *${fixProfile(fix)}* — ${fix.summary}`);
    if (fix.patch) {
      lines.push("", "  ```ts", ...fix.patch.split("\n").map((line) => `  ${line}`), "  ```");
    }
  }

  lines.push("", `\`owlwarden explain ${rule.id}\` prints this in the terminal.`, "");
}

const generated = `${lines.join("\n").replace(/\n{3,}/g, "\n\n").trimEnd()}\n`;

if (process.argv.includes("--check")) {
  const existing = readFileSync(OUTPUT, "utf8");
  if (existing !== generated) {
    process.stderr.write(
      "RULES.md is out of date. Run `node scripts/generate-rules-md.mjs`.\n",
    );
    process.exitCode = 1;
  }
} else {
  writeFileSync(OUTPUT, generated);
  process.stdout.write(`wrote ${OUTPUT}\n`);
}
